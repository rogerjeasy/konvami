import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Lexer, type Token, type Tokens } from 'marked';
import { LANGUAGES, PAGES, type Language, type Page, type Settings } from './pages.ts';

/**
 * The legal pages as the app shows them (6.18). The Markdown under content/ is the one source:
 * the site renders it to HTML, and this turns it into plain data the app draws with its own
 * `Text`, so the two can never say different things. The result is written to
 * apps/mobile/src/legal/documents.generated.ts by `pnpm legal:generate`, and a test fails while
 * the committed file is out of date.
 *
 * The model has only what the content uses: headings, paragraphs, lists, and bold in text.
 * Placeholders such as `{{controller.name}}` stay in the text; the app fills them when it draws.
 */

export type Span = { text: string; bold?: true };
export type Block =
  | { kind: 'heading'; text: string }
  | { kind: 'paragraph'; spans: Span[] }
  | { kind: 'list'; items: Span[][] };
export type LegalDocument = { title: string; blocks: Block[] };

const content = join(dirname(fileURLToPath(import.meta.url)), '..', 'content');

function spansOf(tokens: Token[] | undefined, bold: boolean): Span[] {
  const spans: Span[] = [];
  for (const token of tokens ?? []) {
    if (token.type === 'strong') {
      spans.push(...spansOf((token as Tokens.Strong).tokens, true));
    } else if (token.type === 'em' || token.type === 'link') {
      spans.push(...spansOf((token as Tokens.Em | Tokens.Link).tokens, bold));
    } else if (token.type === 'text' || token.type === 'escape' || token.type === 'codespan') {
      const text = (token as Tokens.Text).text;
      // A text token can hold inline tokens of its own (inside a list item).
      const inner = (token as Tokens.Text).tokens;
      if (inner?.length) spans.push(...spansOf(inner, bold));
      else spans.push(bold ? { text, bold: true } : { text });
    } else {
      throw new Error(`Unsupported inline Markdown in legal content: ${token.type}`);
    }
  }
  // Neighbours with the same weight read as one run of text.
  return spans.reduce<Span[]>((merged, span) => {
    const last = merged[merged.length - 1];
    if (last && Boolean(last.bold) === Boolean(span.bold)) last.text += span.text;
    else merged.push({ ...span });
    return merged;
  }, []);
}

/** One page in one language as blocks. The first heading is the title and is not a block. */
export function parseDocument(markdown: string): LegalDocument {
  let title = '';
  const blocks: Block[] = [];
  for (const token of new Lexer({ gfm: true }).lex(markdown)) {
    if (token.type === 'space') continue;
    if (token.type === 'heading') {
      const heading = token as Tokens.Heading;
      if (heading.depth === 1 && !title) title = heading.text;
      else if (heading.depth === 2) blocks.push({ kind: 'heading', text: heading.text });
      else throw new Error(`Unsupported heading level in legal content: ${heading.raw}`);
    } else if (token.type === 'paragraph') {
      blocks.push({ kind: 'paragraph', spans: spansOf((token as Tokens.Paragraph).tokens, false) });
    } else if (token.type === 'list') {
      const list = token as Tokens.List;
      blocks.push({
        kind: 'list',
        items: list.items.map((item) => spansOf(item.tokens, false)),
      });
    } else {
      throw new Error(`Unsupported Markdown in legal content: ${token.type}`);
    }
  }
  if (!title) throw new Error('A page must start with a level-1 heading');
  return { title, blocks };
}

export type AppDocuments = Record<Language, Record<Page, LegalDocument>>;

export function readDocuments(): AppDocuments {
  const documents = {} as AppDocuments;
  for (const lang of LANGUAGES) {
    documents[lang] = {} as Record<Page, LegalDocument>;
    for (const page of PAGES) {
      documents[lang][page] = parseDocument(
        readFileSync(join(content, page, `${lang}.md`), 'utf8'),
      );
    }
  }
  return documents;
}

/** The source of apps/mobile/src/legal/documents.generated.ts. */
export function generatedSource(settings: Settings, documents = readDocuments()): string {
  return `// Generated by \`pnpm legal:generate\` from apps/site (content/ and site.config.ts). Do not edit.
// The legal pages as the app shows them (6.18); the site publishes the same text as HTML.
import type { LegalDocuments, LegalSettings } from './types';

export const LEGAL_SETTINGS: LegalSettings = ${JSON.stringify(settings, null, 2)};

export const LEGAL_DOCUMENTS: LegalDocuments = ${JSON.stringify(documents, null, 2)};
`;
}
